export const formatUsd = (n: number) =>
  new Intl.NumberFormat("ru-RU", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(n);

export const formatRange = ([a, b]: [number, number]) =>
  `${formatUsd(a)} – ${formatUsd(b)}`;
